"""Repeatable no-key demo in its own PostgreSQL schema. Run from any directory."""
import argparse
import os
from pathlib import Path
import re
import subprocess
import sys
from uuid import uuid4
import psycopg
from psycopg import sql
from psycopg.conninfo import make_conninfo

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from app.db.postgres import DEFAULT_DATABASE_URL

def environment(database_url, schema):
    # Demo is always Fake: inherited paid-model settings/keys cannot activate a provider.
    env = {k: v for k, v in os.environ.items() if not k.startswith("KNOWLEDGEOPS_")}
    url = make_conninfo(database_url, options=f"-c search_path={schema},public")
    reader = make_conninfo(url, user="knowledgeops_agent_reader", password="local-agent-read-only")
    env.update(KNOWLEDGEOPS_DATABASE_URL=url,
        KNOWLEDGEOPS_AGENT_BUSINESS_DATABASE_URL=reader,
        KNOWLEDGEOPS_RETRIEVAL_STRATEGY="hybrid",
        KNOWLEDGEOPS_EMBEDDING_COLLECTION="demo-fake-v1",
        PYTHONUTF8="1")
    return env

def run(args, env):
    subprocess.run([sys.executable, "-B", *args], cwd=ROOT, env=env, check=True)

def ensure_schema(database_url, schema):
    with psycopg.connect(database_url, connect_timeout=5) as db:
        db.execute(sql.SQL("CREATE SCHEMA IF NOT EXISTS {}").format(sql.Identifier(schema)))

def initialize(env):
    run(["scripts/index_documents.py", "--seed-samples", "--report-name", "demo-index"], env)
    run(["scripts/setup_agent_demo.py"], env)

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("command", choices=("init", "serve", "smoke", "test", "evaluate"))
    parser.add_argument("--database-url", default=os.getenv("KNOWLEDGEOPS_DATABASE_URL") or DEFAULT_DATABASE_URL,
                        help="Local PostgreSQL writer connection; prefer the environment for credentials")
    parser.add_argument("--schema", default="ko_demo", help="Demo schema, starting with ko_demo")
    parser.add_argument("--host", default="127.0.0.1")
    parser.add_argument("--port", type=int, default=8000)
    args = parser.parse_args()
    if not re.fullmatch(r"ko_demo[a-z0-9_]{0,48}", args.schema):
        parser.error("Schema must start with ko_demo and contain only lowercase letters, digits or underscores")
    schema = "ko_demo_check_" + uuid4().hex[:16] if args.command in {"smoke", "test"} else args.schema
    env = environment(args.database_url, schema)
    scratch_created = False
    try:
        if args.command == "serve":
            # Do not silently recreate/seed fixtures on every server startup.
            with psycopg.connect(args.database_url, connect_timeout=5) as db:
                ready = db.execute("SELECT to_regclass(%s)", (schema + ".documents",)).fetchone()[0]
                if ready is None:
                    parser.error("Run python scripts/demo.py init with the same database/schema first")
            print("Fake demo: http://" + args.host + ":" + str(args.port) + "/docs", flush=True)
            run(["-m", "uvicorn", "app.main:app", "--host", args.host, "--port", str(args.port)], env)
        else:
            ensure_schema(args.database_url, schema)
            scratch_created = args.command in {"smoke", "test"}
            if args.command in {"init", "smoke"}:
                initialize(env)
            if args.command == "smoke":
                run(["scripts/smoke_demo.py"], env)
            elif args.command == "test":
                run(["scripts/setup_agent_demo.py"], env)
                env.update(KNOWLEDGEOPS_TEST_DATABASE_URL=env["KNOWLEDGEOPS_DATABASE_URL"],
                    KNOWLEDGEOPS_TEST_VECTOR_DATABASE_URL=env["KNOWLEDGEOPS_DATABASE_URL"],
                    KNOWLEDGEOPS_TEST_AGENT_READER_URL=env["KNOWLEDGEOPS_AGENT_BUSINESS_DATABASE_URL"])
                run(["-m", "pytest", "-p", "no:cacheprovider"], env)
            elif args.command == "evaluate":
                run(["scripts/evaluate_rag.py", "--split", "dev"], env)
            elif args.command == "init":
                print("Ready: 14 simulated documents. Next: python scripts/demo.py serve", flush=True)
    except KeyboardInterrupt:
        parser.exit(0, "Demo stopped.\n")
    except psycopg.Error:
        parser.exit(1, "PostgreSQL unavailable or setup failed. Start Docker, then docker compose up -d vectors.\n")
    except subprocess.CalledProcessError as exc:
        parser.exit(exc.returncode, "Command failed; see diagnostics above.\n")
    finally:
        if scratch_created:
            # Only drop the random scratch schema generated by this invocation.
            try:
                with psycopg.connect(args.database_url, connect_timeout=5) as db:
                    db.execute(sql.SQL("DROP SCHEMA IF EXISTS {} CASCADE").format(sql.Identifier(schema)))
            except psycopg.Error:
                print("Scratch cleanup failed; remove only the generated schema: " + schema, file=sys.stderr)

if __name__ == "__main__":
    main()
